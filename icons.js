// The right arrow is just the left arrow flipped: we reverse every row
PIXEL_ICONS.arrowRight = PIXEL_ICONS.arrowLeft.map((row) => row.split("").reverse().join(""));


// Turns an icon's text picture into an <svg> image that can be put on the page.
// The icon takes the text color of its parent (fill="currentColor").
function pixelIcon(name) {
  const rows = PIXEL_ICONS[name] || PIXEL_ICONS.other;

  // Build the drawing instructions. Neighbouring "#" in a row are drawn as one
  // rectangle: "M x y" = move to the pixel, "h" = go right, "v" = go down, "z" = close.
  let path = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let width = 1;
        while (row[x + width] === "#") {
          width++;
        }
        path += "M" + x + " " + y + "h" + width + "v1h-" + width + "z";
        x += width;
      } else {
        x++;
      }
    }
  });

  // SVG elements need a special "namespace", so we use createElementNS
  const svgNS = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(svgNS, "svg");
  svg.setAttribute("viewBox", "0 0 12 12");
  svg.setAttribute("class", "pixel-icon");
  svg.setAttribute("aria-hidden", "true"); // screen readers skip decorative icons
  svg.setAttribute("shape-rendering", "crispEdges"); // keep pixel edges sharp

  const shape = document.createElementNS(svgNS, "path");
  shape.setAttribute("d", path);
  shape.setAttribute("fill", "currentColor");
  svg.appendChild(shape);
  return svg;
}

// Finds every element like <span data-icon="coin"></span> in the HTML
// and puts the matching icon inside it
function fillStaticIcons() {
  for (const holder of document.querySelectorAll("[data-icon]")) {
    holder.appendChild(pixelIcon(holder.dataset.icon));
  }
}
